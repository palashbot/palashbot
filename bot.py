# =========================================================
# MESSAGE REPLY
# =========================================================

async def reply(update: Update, context: ContextTypes.DEFAULT_TYPE):

    if not update.message:
        return

    if not update.message.text:
        return

    original_text = update.message.text.strip()

    # বাংলা/ইংরেজি ছোট হাতের করা
    text = original_text.lower()

    # -------------------------
    # Exact match
    # -------------------------

    if text in ANSWERS:

        await update.message.reply_text(
            ANSWERS[text]
        )

        return

    # -------------------------
    # Keyword match
    # -------------------------

    if "তোমার নাম" in text:

        await update.message.reply_text(
            "🤖 আমার নাম Sweatheart। ❤️"
        )

        return

    if "কে বানিয়েছে" in text or "কে বানায়" in text:

        await update.message.reply_text(
            "🤖 আমাকে Palash তৈরি করেছে। ❤️"
        )

        return

    if "কেমন আছ" in text:

        await update.message.reply_text(
            "😊 আমি ভালো আছি। তুমি কেমন আছো?"
        )

        return

    if "ধন্যবাদ" in text or "thanks" in text:

        await update.message.reply_text(
            "❤️ স্বাগতম!"
        )

        return

    if "গুডবাই" in text or "goodbye" in text:

        await update.message.reply_text(
            "👋 ভালো থেকো। আবার কথা হবে!"
        )

        return

    # -------------------------
    # Unknown message
    # -------------------------

    await update.message.reply_text(
        "🤔 এই প্রশ্নের উত্তর এখনো আমার database-এ নেই।\n\n"
        f"তুমি লিখেছ: {original_text}\n\n"
        "আরেকটা প্রশ্ন করে দেখো 😊"
    )


# =========================================================
# ERROR HANDLER
# =========================================================

async def error_handler(
    update: object,
    context: ContextTypes.DEFAULT_TYPE
):

    print(
        "Telegram error:",
        repr(context.error)
    )


# =========================================================
# MAIN
# =========================================================

def main():

    print("===================================")
    print("Starting Sweatheart Bot...")
    print("===================================")

    # TOKEN check
    if not TOKEN:

        print("ERROR: BOT_TOKEN পাওয়া যায়নি!")

        return

    # -------------------------
    # Start Flask
    # -------------------------

    web_thread = threading.Thread(
        target=run_web,
        daemon=True
    )

    web_thread.start()

    print("Flask web server started.")

    # -------------------------
    # Telegram Application
    # -------------------------

    application = (
        Application
        .builder()
        .token(TOKEN)
        .build()
    )

    # -------------------------
    # Handlers
    # -------------------------

    application.add_handler(
        CommandHandler(
            "start",
            start
        )
    )

    application.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            reply
        )
    )

    # Error handler
    application.add_error_handler(
        error_handler
    )

    print("===================================")
    print("Sweatheart Bot is running!")
    print("Telegram polling started.")
    print("===================================")

    # -------------------------
    # Start polling
    # -------------------------

    application.run_polling(
        drop_pending_updates=True
    )


# =========================================================
# START PROGRAM
# =========================================================

if __name__ == "__main__":
    main()
