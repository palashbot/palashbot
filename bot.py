# Message Reply
# =========================

async def reply(update: Update, context: ContextTypes.DEFAULT_TYPE):

    if not update.message or not update.message.text:
        return

    original_text = update.message.text
    text = original_text.lower().strip()

    # ১. Exact match
    if text in ANSWERS:
        await update.message.reply_text(ANSWERS[text])
        return

    # ২. Common variations / keyword matching
    if "তোমার নাম" in text:
        await update.message.reply_text(
            "🤖 আমার নাম Sweatheart। ❤️"
        )
        return

    if "তুমি কে" in text or "কে তুমি" in text:
        await update.message.reply_text(
            "🤖 আমি Sweatheart Bot। তোমার সাথে কথা বলার জন্য তৈরি। ❤️"
        )
        return

    if "জোক" in text or "জোকস" in text:
        await update.message.reply_text(
            "😂 শিক্ষক: সবচেয়ে অলস কে?\n"
            "ছাত্র: যে উত্তর দিতে চায় না! 😆"
        )
        return

    if "কেমন আছ" in text:
        await update.message.reply_text(
            "😊 আমি ভালো আছি। তুমি কেমন আছো?"
        )
        return

    if "ধন্যবাদ" in text or "thanks" in text:
        await update.message.reply_text(
            "❤️ স্বাগতম!"
        )
        return

    if "গুডবাই" in text or "goodbye" in text:
        await update.message.reply_text(
            "👋 ভালো থেকো। আবার কথা হবে!"
        )
        return

    # ৩. Unknown question
    await update.message.reply_text(
        "🤔 এই প্রশ্নের উত্তর এখনো আমার database-এ নেই।\n\n"
        f"তুমি লিখেছ: {original_text}\n\n"
        "আরেকটা প্রশ্ন করে দেখো 😊"
    )


