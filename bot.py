# Main
# =========================

def main():

    if not TOKEN:
        print("❌ BOT_TOKEN পাওয়া যায়নি!")
        return

    print("===================================")
    print("Starting Sweatheart Bot...")
    print("===================================")

    # Web server
    threading.Thread(
        target=run_web,
        daemon=True
    ).start()

    print("Flask web server started.")

    # Telegram application
    application = (
        Application
        .builder()
        .token(TOKEN)
        .build()
    )

    # /start
    application.add_handler(
        CommandHandler("start", start)
    )

    # Normal messages
    application.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            reply
        )
    )

    print("Telegram bot is starting...")
    print("Sweatheart Bot is running! ❤️")

    application.run_polling()


if __name__ == "__main__":
    main()
